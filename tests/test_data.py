"""Lightweight data/label checks: no model or corpus downloads are required."""
import json
from pathlib import Path
import tempfile
import unittest

import numpy as np
import pandas as pd

from idiom_subspace.data import (SplitFeasibilityError, build_items, load_corpus, normalize_phrase,
                                 normalize_idiom_type, split_corpus)
from idiom_subspace.labels import build_labels, export_annotation_sample, validate_annotations


class DataTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.folder = Path(self.temp.name)

    def tearDown(self):
        self.temp.cleanup()

    def corpus(self, records):
        path = self.folder / "corpus.json"
        path.write_text(json.dumps(records, ensure_ascii=False), encoding="utf8")
        return load_corpus(path)

    @staticmethod
    def record(i, **overrides):
        record = dict(id=str(i), idiom=f"বাগধারা {i}", figurative_meaning_en=f"Anger and frustration {i}",
                      # Distinct glosses: identical model inputs are linked by the input-disjoint split.
                      figurative_meaning_bn="রাগ" if i == 0 else f"রাগ {i}",
                      literal_meaning="আক্ষরিক বাংলা অর্থ (literal gloss)",
                      example_sentences_in_bangla=[f"সে বাগধারা {i} বলে।"],
                      example_sentences_in_english=[f"He says expression {i}."],
                      similar_in_english=[f"expression {i}"], tags=["anger"], usage_domain=["social"],
                      sentiment="negative", cultural_significance="0", religious_significance="0",
                      historical_significance="0", frequency="common")
        record.update(overrides)
        return record

    def test_missing_counterpart_duplicate_senses_and_stable_ids(self):
        records = [self.record(0, similar_in_english=[]),
                   self.record(1, idiom="বাগধারা 0"), self.record(2)]
        df, audit = self.corpus(records + [records[2]])
        self.assertEqual(len(df), 4)
        self.assertEqual(audit["absent_counterparts"], 1)
        self.assertEqual(audit["exact_duplicate_rows"], 1)
        self.assertTrue(df.idiom_id.is_unique)
        self.assertEqual(df.iloc[0].idiom_group, df.iloc[1].idiom_group)
        self.assertFalse(df.iloc[0].anchored)
        reversed_df, _ = self.corpus(list(reversed(records + [records[2]])))
        self.assertEqual(set(df.idiom_id), set(reversed_df.idiom_id))
        self.assertTrue(df.lit_en.eq("").all())
        self.assertIn("বাংলা", df.iloc[0].lit_bn)
        self.assertFalse(df.cultural.any())

    def test_second_exact_example_uses_aligned_translation(self):
        row = self.record(0, example_sentences_in_bangla=["অন্য কথা", "বাগধারা 0 আছে"],
                          example_sentences_in_english=["First translation", "Aligned second translation"])
        df, audit = self.corpus([row])
        self.assertEqual(df.iloc[0].example_index, 1)
        self.assertEqual(df.iloc[0].en_ex, "Aligned second translation")
        self.assertEqual(audit["first_example_exact_span"], 0)
        self.assertEqual(audit["any_example_exact_span"], 1)

    def test_alias_sidecars_preserve_legacy_record_and_feature_identities(self):
        from idiom_subspace.extraction import fingerprint
        base = self.record(0)
        before, _ = self.corpus([base])
        # Golden ID generated by the pre-fix fb92cf3 loader for this fixture.
        self.assertEqual(before.iloc[0].idiom_id, "idiom_813342015af5972ad789")
        with_aliases = dict(base, alternative_idioms=["বাগ ধারা 0", "সম্পূর্ণ অন্য অভিব্যক্তি"])
        after, _ = self.corpus([with_aliases])
        self.assertEqual(before.idiom_id.tolist(), after.idiom_id.tolist())
        self.assertEqual(after.iloc[0].alternative_idioms, with_aliases["alternative_idioms"])
        old_items, new_items = build_items(before), build_items(after)
        cols = ["item_id", "idiom_id", "source_id", "condition", "lang", "text", "span", "pool_target"]
        pd.testing.assert_frame_equal(old_items[cols], new_items[cols])
        self.assertEqual(fingerprint(old_items, {}), fingerprint(new_items, {}))

    def test_spacing_variants_are_disjoint_without_merging_semantic_alternatives(self):
        records = [self.record(i) for i in range(24)]
        records[0].update(idiom="এক রত্তি", alternative_idioms=["একরত্তি", records[2]["idiom"]])
        records[1].update(idiom="একরত্তি", alternative_idioms=["এক রত্তি"])
        df, _ = self.corpus(records)
        self.assertEqual(normalize_idiom_type("এক রত্তি"), normalize_idiom_type("একরত্তি"))
        self.assertEqual(df.iloc[0].idiom_group, df.iloc[1].idiom_group)
        for mode in ("input_disjoint", "strict", "idiom_only"):
            result = split_corpus(df, seed=7, mode=mode, fractions=(.4, .25, .1, .25))
            self.assertEqual(result.iloc[0].component_id, result.iloc[1].component_id)
            self.assertNotEqual(result.iloc[0].component_id, result.iloc[2].component_id)
            report = result.attrs["split_report"]
            self.assertEqual(report["cross_split_spelling_variant_groups"], 0)
            self.assertEqual(report["alias_audit"]["spelling_equivalent_entries"], 2)
            self.assertEqual(report["alias_audit"]["semantic_alternatives_not_linked"], 1)

    def test_transitive_all_counterparts_and_duplicate_idiom_grouping(self):
        records = [self.record(i) for i in range(24)]
        records[0]["similar_in_english"] = ["alpha", "beta"]
        records[1]["similar_in_english"] = ["gamma", " Beta. "]
        records[2]["similar_in_english"] = ["gamma", "delta"]
        records[3]["idiom"] = records[2]["idiom"]
        records[3]["similar_in_english"] = []
        df, _ = self.corpus(records)
        split = split_corpus(df, seed=7, mode="counterpart_closure")
        self.assertEqual(split.attrs["split_report"]["mode"], "strict")
        self.assertEqual(split.iloc[:4].component_id.nunique(), 1)
        self.assertEqual(len(split), len(df))
        self.assertEqual(split.attrs["split_report"]["overlapping_counterparts"], 0)
        self.assertEqual(set(split.split), {"space", "probe", "validation", "test"})
        shuffled = split_corpus(df.sample(frac=1, random_state=3), seed=7, mode="strict")
        self.assertEqual(split.set_index("idiom_id").split.to_dict(), shuffled.set_index("idiom_id").split.to_dict())
        # Default input-disjoint split: only the probed (first) counterpart and the
        # idiom type link records; a shared secondary counterpart ("beta") does not.
        default = split_corpus(df, seed=7)
        self.assertEqual(default.attrs["split_report"]["mode"], "input_disjoint")
        self.assertEqual(default.iloc[1:4].component_id.nunique(), 1)
        self.assertNotEqual(default.iloc[0].component_id, default.iloc[1].component_id)
        self.assertEqual(default.attrs["split_report"]["cross_split_identical_inputs"], 0)

    def test_input_disjoint_links_identical_inputs_and_form_variants_only(self):
        records = [self.record(i) for i in range(24)]
        records[4]["figurative_meaning_en"] = records[5]["figurative_meaning_en"]      # identical en-para input
        records[6].update(idiom="তেঁদড়", alternative_idioms=["ত্যাঁদড়", records[9]["idiom"]])
        records[7].update(idiom="ত্যাঁদড়")                                               # listed spelling variant
        records[10]["similar_in_english"] = [records[11]["similar_in_english"][0], "secondary only"]
        records[12]["similar_in_english"] = ["unique twelve", "secondary only"]
        records[13].update(idiom="বাগ-ধারা 0")                                            # hyphen variant of record 0
        df, _ = self.corpus(records)
        split = split_corpus(df, seed=3)
        component = split.component_id.tolist()
        self.assertEqual(component[4], component[5])
        self.assertEqual(component[6], component[7])
        self.assertNotEqual(component[6], component[9])      # a listed *different* idiom is not merged
        self.assertEqual(component[10], component[11])       # same probed (first) counterpart
        self.assertNotEqual(component[10], component[12])    # a shared secondary counterpart does not link
        self.assertEqual(normalize_idiom_type("বাগ-ধারা 0"), normalize_idiom_type("বাগধারা 0"))
        report = split.attrs["split_report"]
        self.assertEqual(report["cross_split_identical_inputs"], 0)
        self.assertEqual(report["form_variant_links"], 1)
        self.assertEqual(report["alias_audit"]["form_variant_entries"], 1)
        loose = split_corpus(df, seed=3, mode="idiom_only")
        self.assertGreaterEqual(loose.attrs["split_report"]["cross_split_identical_inputs"], 0)

    def test_infeasible_strict_split_fails_without_dropping_giant(self):
        rows = [self.record(i, similar_in_english=["shared"] if i < 15 else [f"unique {i}"])
                for i in range(24)]
        df, _ = self.corpus(rows)
        with self.assertRaises(SplitFeasibilityError) as ctx:
            split_corpus(df, fractions=(.4, .25, .1, .25))
        self.assertEqual(ctx.exception.report["largest_component"], 15)
        self.assertEqual(ctx.exception.report["records"], 24)
        strict = split_corpus(df, fractions=(.65, .15, .05, .15), mode="strict")
        self.assertTrue(strict.iloc[:15].split.eq("space").all())
        exploratory = split_corpus(df, fractions=(.4, .25, .1, .25), mode="idiom_only")
        self.assertGreater(exploratory.attrs["split_report"]["overlapping_counterparts"], 0)

    def test_items_preserve_invalid_spans_and_missing_counterparts(self):
        df, _ = self.corpus([self.record(0, similar_in_english=[]),
                             self.record(1, example_sentences_in_bangla=["সম্পূর্ণ ভিন্ন বাক্য"])])
        items = build_items(df)
        self.assertTrue(items.item_id.is_unique)
        self.assertEqual(len(items[items.condition.eq("en-idiom")]), 1)
        bad = items[items.condition.eq("bn-fig") & items.idiom_id.eq(df.iloc[1].idiom_id)].iloc[0]
        self.assertFalse(bad.span_found)
        self.assertEqual(bad.pool_target, "span")
        self.assertEqual(bad.span_start, -1)
        context = items[items.condition.eq("bn-context")]
        self.assertEqual(len(context), 1)
        self.assertEqual(context.iloc[0].pool_target, "context")
        self.assertEqual(context.iloc[0].span, "[MASK]")
        self.assertEqual(len(items[items.condition.eq("bn-sentence")]), 2)
        self.assertTrue(items[items.condition.eq("en-trans")].pool_target.eq("sentence").all())

    def test_controls_require_approval_known_record_and_exact_span(self):
        df, _ = self.corpus([self.record(0)])
        controls = pd.DataFrame([
            dict(idiom_id=df.iloc[0].idiom_id, condition="bn-rom", lang="bn-Latn", text="bagdhara", span="bagdhara", approved="yes"),
            dict(idiom_id="unknown", condition="bn-lit", lang="bn", text="bad", span="bad", approved="false"),
        ])
        path = self.folder / "controls.csv"
        controls.to_csv(path, index=False)
        items = build_items(df, path)
        self.assertEqual(len(items[items.condition.eq("bn-rom")]), 1)
        self.assertEqual(items.attrs["item_audit"]["controls"]["unapproved_rows"], 1)
        controls.loc[0, "span"] = "missing"
        controls.to_csv(path, index=False)
        with self.assertRaisesRegex(ValueError, "exact span"):
            build_items(df, path)

    def test_labels_fit_space_only_and_literal_reuses_taxonomy(self):
        records = [self.record(i) for i in range(9)]
        glosses = ["Anger frustration rage", "Anger rage furious", "Fear terror anxiety", "Fear anxiety panic",
                   "Joy pleasure happiness", "Joy happiness delight", "Anger rage", "Fear terror", "xylophonic zephyrology"]
        sentiments = ["negative", "positive", "neutral", "mixed", "negative", "positive", "negative", "neutral", "unknown"]
        for i, row in enumerate(records):
            row["figurative_meaning_en"] = glosses[i]
            row["literal_meaning_en"] = glosses[i] if i != 7 else "বাংলা অর্থ"
            row["sentiment"] = sentiments[i]
        records[6]["tags"] = ["unseen tag"]
        records[6]["usage_domain"] = ["unseen domain"]
        records[8]["tags"] = ["anger", "joy"]
        df, _ = self.corpus(records)
        df["split"] = ["space"] * 6 + ["probe", "validation", "test"]
        labeled, report, artifacts = build_labels(df, k=3)
        self.assertEqual(len(artifacts["train_indices"]), 6)
        self.assertNotIn("xylophonic", artifacts["vectorizer"].vocabulary_)
        valid = labeled.L.ge(0)
        np.testing.assert_array_equal(labeled.loc[valid, "F"], labeled.loc[valid, "L"])
        self.assertEqual(labeled.iloc[7].L, -1)
        self.assertEqual(labeled.iloc[8].F, -1)
        self.assertEqual(labeled.iloc[6].Ft, -1)
        self.assertEqual(labeled.iloc[6].D, -1)
        self.assertEqual(labeled.iloc[8].S, -1)
        self.assertEqual(len(set(labeled.iloc[:6].S)), 4)
        self.assertTrue(report["same_taxonomy_for_F_and_L"])
        self.assertEqual(report["literal_non_english_rejected"], 1)
        self.assertEqual(labeled.iloc[8].Ft_labels, ("anger", "joy"))

    def test_annotation_validation_joins_ids_not_row_order(self):
        df, _ = self.corpus([self.record(i) for i in range(4)])
        path = self.folder / "annotations.csv"
        template = export_annotation_sample(df, path, n=4)
        report = validate_annotations(path)
        self.assertEqual(report["status"], "incomplete")
        self.assertIsNone(report["fields"]["F"]["kappa"])
        template["annotator_id"] = template.annotation_slot.map({1: "alice", 2: "bob"})
        for field in ("F", "L", "S", "D", "Ft"):
            template[f"human_{field}"] = [str(i // 2 % 2) for i in range(len(template))]
        template.sample(frac=1, random_state=9).to_csv(path, index=False)
        report = validate_annotations(path)
        self.assertEqual(report["status"], "complete")
        self.assertEqual(report["fields"]["F"]["kappa"], 1.0)
        template.loc[1, "annotator_id"] = "alice"
        template.to_csv(path, index=False)
        with self.assertRaisesRegex(ValueError, "independent"):
            validate_annotations(path)


